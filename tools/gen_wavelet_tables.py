"""The WAVELET engine's tables (firmware/src/wavelet_tables.h), from tools/wavelets.json (the filter
coefficients of the Wavelet Synthesizer, made with PyWavelets, MIT) and a few fixed-point curves:

  WAV_H / WAV_G   the analysis low-pass h and high-pass g of each wavelet, Q28, zero-padded to WAV_MAXL
  WAV_L           the filter lengths
  WAV_SOFTPLUS    ln(1 + e^4x) / 4 for x = -4 .. 10 in steps of 1/8, Q8 (the filter's knee, in bands)
  WAV_RESBUMP     exp(-x^2 / 0.72) for x = 0 .. 3 in steps of 1/16, Q15 (the resonance peak)
  WAV_POW2        2^(k / 64), k = 0 .. 64, Q14 (dB to gain, sparsity)
  WAV_LOG2        log2(1 + k / 64) * 256, k = 0 .. 64, Q8 (sparsity)

  python3 tools/gen_wavelet_tables.py firmware/src/wavelet_tables.h
The header is committed: the host tests and the browser build need no Python."""
import json
import math
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MAXL = 40


def arr(name, ctype, vals, per=8):
    out = [f"static const {ctype} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    out.append("};")
    return out


def q(x, bits, lim):
    v = int(round(x * (1 << bits)))
    return max(-lim, min(lim, v))


def main(path):
    w = json.loads((HERE / "wavelets.json").read_text())
    order, filters = w["order"], w["h"]
    L = ["/* generated by tools/gen_wavelet_tables.py from tools/wavelets.json: do not edit */",
         "#pragma once", "#include <stdint.h>", f"#define WAV_NW {len(order)}", f"#define WAV_MAXL {MAXL}", ""]
    L.append(f"static const uint8_t WAV_L[WAV_NW] = {{{', '.join(str(len(filters[n])) for n in order)}}};")
    L.append("static const int32_t WAV_H[WAV_NW][WAV_MAXL] = {")
    for n in order:
        h = filters[n]
        assert len(h) <= MAXL
        vals = [q(v, 28, (1 << 31) - 1) for v in h] + [0] * (MAXL - len(h))
        L.append(f"    /* {n} */ {{" + ", ".join(str(v) for v in vals) + "},")
    L.append("};")
    L.append("static const int32_t WAV_G[WAV_NW][WAV_MAXL] = {")
    for n in order:
        h = filters[n]
        g = [(-1 if (i & 1) else 1) * h[len(h) - 1 - i] for i in range(len(h))]
        vals = [q(v, 28, (1 << 31) - 1) for v in g] + [0] * (MAXL - len(h))
        L.append(f"    /* {n} */ {{" + ", ".join(str(v) for v in vals) + "},")
    L.append("};")
    names = ", ".join('"' + n.upper() + '"' for n in order)
    L.append(f"static const char *const N_WVLT[] = {{{names}}};")
    L.append("")
    sp = []
    for k in range(113):
        x = -4 + k / 8
        v = x if x > 10 else math.log(1 + math.exp(4 * x)) / 4
        sp.append(q(v, 8, 32767))
    L += arr("WAV_SOFTPLUS", "int16_t", sp, 12)
    L += arr("WAV_RESBUMP", "int16_t", [q(math.exp(-(k / 16) ** 2 / 0.72), 15, 32767) for k in range(49)], 12)
    L += arr("WAV_POW2", "uint16_t", [int(round(2 ** (k / 64) * 16384)) for k in range(65)], 12)
    L += arr("WAV_LOG2", "uint16_t", [int(round(math.log2(1 + k / 64) * 256)) for k in range(65)], 12)
    Path(path).write_text("\n".join(L) + "\n")
    print(f"{path}: {len(order)} wavelets (L up to {max(len(filters[n]) for n in order)})")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else HERE.parent / "firmware" / "src" / "wavelet_tables.h")
